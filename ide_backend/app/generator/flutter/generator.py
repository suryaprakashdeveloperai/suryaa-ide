import os
import re
from pathlib import Path
from typing import Dict, Any
from .styles import generate_theme_dart
from .widgets import render_component

def to_pascal_case(text: str) -> str:
    cleaned = re.sub(r'[^a-zA-Z0-9]+', ' ', text)
    parts = cleaned.split()
    if not parts:
        return "App"
    return "".join(p.capitalize() for p in parts)

class FlutterProjectGenerator:
    """
    Generates a production-grade, independently buildable Flutter application
    following strict Clean Architecture & MVVM principles.
    """
    def __init__(self, schema: Dict[str, Any]):
        self.schema = schema
        self.metadata = schema.get("metadata", {})
        raw_name = self.metadata.get("name", "Flutter App")
        self.project_name = raw_name.lower().replace(" ", "_").replace("-", "_")
        self.app_title = raw_name
        pascal = to_pascal_case(raw_name)
        self.app_class_name = pascal if pascal.endswith("App") else f"{pascal}App"
        self.theme = schema.get("theme", {})
        self.screens = schema.get("screens", [])
        self.components = schema.get("components", {})
        self.workflows = schema.get("workflows", [])

    def generate_all(self, output_dir: Path) -> Dict[str, str]:
        """
        Generates and writes the entire Flutter project files to output_dir.
        Returns a dictionary of relative file paths to their generated contents.
        """
        files: Dict[str, str] = {}
        
        # 1. Pubspec & Android Manifest
        files["pubspec.yaml"] = self.generate_pubspec()
        files["analysis_options.yaml"] = self.generate_analysis_options()
        files["README.md"] = self.generate_readme()
        files["android/app/src/main/AndroidManifest.xml"] = self.generate_android_manifest()
        
        # 2. App root
        files["lib/main.dart"] = self.generate_main_dart()
        files["lib/bootstrap.dart"] = self.generate_bootstrap_dart()
        files["lib/app/app.dart"] = self.generate_app_dart()
        files["lib/app/theme/app_theme.dart"] = generate_theme_dart(
            self.theme.get("activePreset", "material3"),
            self.theme.get("tokens", {}),
            mode=self.theme.get("mode", "dark")
        )
        
        # 3. Data layer
        files["lib/data/services/api_client.dart"] = self.generate_api_client()
        
        # 4. Features / Screens (Views and ViewModels)
        for screen in self.screens:
            sname = screen.get("name", "HomeScreen")
            sname_snake = sname.lower().replace("screen", "").replace(" ", "_")
            if not sname_snake:
                sname_snake = "home"
                
            files[f"lib/features/{sname_snake}/view_models/{sname_snake}_view_model.dart"] = self.generate_view_model(screen)
            files[f"lib/features/{sname_snake}/views/{sname_snake}_view.dart"] = self.generate_view(screen)
            
        # Write files to disk
        for rel_path, content in files.items():
            dest = output_dir / rel_path
            dest.parent.mkdir(parents=True, exist_ok=True)
            with open(dest, "w", encoding="utf-8") as f:
                f.write(content)
                
        # Auto-format dart files with Google Dart SDK if available
        try:
            from ...core.config import settings
            import subprocess
            if settings.dart_path and Path(settings.dart_path).exists():
                subprocess.run([settings.dart_path, "format", str(output_dir / "lib")], capture_output=True, timeout=15)
        except Exception:
            pass

        return files

    def generate_pubspec(self) -> str:
        return f"""name: {self.project_name}
description: "Generated by Visual Flutter Full-Stack IDE"
publish_to: "none"
version: 1.0.0+1

environment:
  sdk: ">=3.0.0 <4.0.0"

dependencies:
  flutter:
    sdk: flutter
  http: ^1.2.0
  shared_preferences: ^2.2.3
  fl_chart: ^0.66.0
  video_player: ^2.8.2

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^3.0.0

flutter:
  uses-material-design: true
"""

    def generate_android_manifest(self) -> str:
        android = self.metadata.get("android", {})
        pkg = android.get("packageName", self.metadata.get("packageName", "com.example.app"))
        app_name = android.get("appName", self.app_title)
        permissions = android.get("permissions", ["android.permission.INTERNET"])
        
        perms_xml = "\n".join([f'    <uses-permission android:name="{p}" />' for p in permissions])
        
        return f"""<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="{pkg}">
{perms_xml}
    <application
        android:label="{app_name}"
        android:name="${{applicationName}}"
        android:icon="@mipmap/ic_launcher">
        <activity
            android:name=".MainActivity"
            android:exported="true"
            android:launchMode="singleTop"
            android:theme="@style/LaunchTheme">
            <intent-filter>
                <action android:name="android.intent.action.MAIN"/>
                <category android:name="android.intent.category.LAUNCHER"/>
            </intent-filter>
        </activity>
    </application>
</manifest>
"""

    def generate_analysis_options(self) -> str:
        return """include: package:flutter_lints/flutter.yaml

linter:
  rules:
    prefer_const_constructors: true
    prefer_const_literals_to_create_immutables: true
    avoid_print: false
"""

    def generate_main_dart(self) -> str:
        return f"""import 'package:flutter/material.dart';
import 'bootstrap.dart';
import 'app/app.dart';

void main() async {{
  WidgetsFlutterBinding.ensureInitialized();
  await bootstrap();
  runApp(const {self.app_class_name}());
}}
"""

    def generate_bootstrap_dart(self) -> str:
        return """// Global startup configuration and service initialization
import 'data/services/api_client.dart';

final apiClient = ApiClient();

Future<void> bootstrap() async {
  // Pre-startup initializations (caches, tokens, telemetry)
}
"""

    def generate_app_dart(self) -> str:
        theme_mode = self.theme.get("mode", "dark")
        flutter_theme_mode = "ThemeMode.light" if theme_mode == "light" else "ThemeMode.dark"

        imports = [
            "import 'package:flutter/material.dart';",
            "import 'theme/app_theme.dart';"
        ]
        routes_entries = []
        first_screen_view = "HomeScreenView(viewModel: HomeScreenViewModel())"

        for i, screen in enumerate(self.screens):
            sname = screen.get("name", f"Screen{i+1}")
            sname_clean = sname.replace(" ", "")
            sname_snake = sname.lower().replace("screen", "").replace(" ", "_")
            if not sname_snake:
                sname_snake = f"screen_{i+1}"
            route = screen.get("route", f"/{sname_snake}")
            if not route.startswith("/"):
                route = f"/{route}"
            
            imports.append(f"import '../features/{sname_snake}/views/{sname_snake}_view.dart';")
            imports.append(f"import '../features/{sname_snake}/view_models/{sname_snake}_view_model.dart';")
            
            view_inst = f"{sname_clean}View(viewModel: {sname_clean}ViewModel())"
            if i == 0:
                first_screen_view = view_inst
                routes_entries.append(f"        '/': (context) => {view_inst},")
            if route != "/":
                routes_entries.append(f"        '{route}': (context) => {view_inst},")

        unique_imports = sorted(list(set(imports)))
        imports_str = "\n".join(unique_imports)
        routes_str = "\n".join(routes_entries)

        if len(self.screens) > 1:
            routing_code = f"""initialRoute: '/',
      routes: {{
{routes_str}
      }},"""
        else:
            routing_code = f"home: {first_screen_view},"

        return f"""{imports_str}

class {self.app_class_name} extends StatelessWidget {{
  const {self.app_class_name}({{super.key}});

  @override
  Widget build(BuildContext context) {{
    return MaterialApp(
      title: '{self.app_title}',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.lightTheme,
      darkTheme: AppTheme.darkTheme,
      themeMode: {flutter_theme_mode},
      {routing_code}
    );
  }}
}}
"""

    def generate_api_client(self) -> str:
        return """import 'dart:convert';
import 'package:http/http.dart' as http;

class ApiClient {
  final String baseUrl;

  ApiClient({this.baseUrl = 'http://127.0.0.1:8000'});

  Future<dynamic> get(String endpoint) async {
    final response = await http.get(Uri.parse('$baseUrl$endpoint'));
    if (response.statusCode >= 200 && response.statusCode < 300) {
      return json.decode(response.body);
    }
    throw Exception('API Error: ${response.statusCode} - ${response.body}');
  }

  Future<dynamic> post(String endpoint, Map<String, dynamic> data) async {
    final response = await http.post(
      Uri.parse('$baseUrl$endpoint'),
      headers: {'Content-Type': 'application/json'},
      body: json.encode(data),
    );
    if (response.statusCode >= 200 && response.statusCode < 300) {
      return json.decode(response.body);
    }
    throw Exception('API Error: ${response.statusCode} - ${response.body}');
  }
}
"""

    def generate_view_model(self, screen: Dict[str, Any]) -> str:
        name = screen.get("name", "HomeScreen").replace(" ", "")
        state_vars = screen.get("stateVariables", [])
        
        var_decls = []
        var_getters = []
        for v in state_vars:
            vname = v.get("name", "state")
            vtype = v.get("type", "dynamic")
            init = v.get("initialValue", "null")
            if isinstance(init, str) and vtype == "String":
                init = f"'{init}'"
            elif isinstance(init, bool):
                init = str(init).lower()
            var_decls.append(f"  {vtype} _{vname} = {init};")
            var_getters.append(f"  {vtype} get {vname} => _{vname};")

        vars_rendered = "\n".join(var_decls + var_getters)

        return f"""import 'package:flutter/material.dart';
import '../../../bootstrap.dart';

class {name}ViewModel extends ChangeNotifier {{
  bool _isLoading = false;
  bool get isLoading => _isLoading;

{vars_rendered}

  void setLoading(bool val) {{
    _isLoading = val;
    notifyListeners();
  }}

  void executeAction(String actionName) async {{
    // Visual logic triggers
    setLoading(true);
    try {{
      // Handled by workflow engine
    }} catch (e) {{
      debugPrint('Action error: $e');
    }} finally {{
      setLoading(false);
    }}
  }}
}}
"""

    def generate_view(self, screen: Dict[str, Any]) -> str:
        name = screen.get("name", "HomeScreen").replace(" ", "")
        sname_snake = screen.get("name", "home").lower().replace("screen", "").replace(" ", "_")
        if not sname_snake:
            sname_snake = "home"
        root_id = screen.get("rootComponentId", "")
        
        body_widget = render_component(root_id, self.components, indent_level=3)

        return f"""import 'package:flutter/material.dart';
import 'package:fl_chart/fl_chart.dart';
import '../view_models/{sname_snake}_view_model.dart';

class {name}View extends StatelessWidget {{
  final {name}ViewModel viewModel;

  const {name}View({{super.key, required this.viewModel}});

  @override
  Widget build(BuildContext context) {{
    return ListenableBuilder(
      listenable: viewModel,
      builder: (context, _) {{
        return {body_widget};
      }},
    );
  }}
}}
"""

    def generate_readme(self) -> str:
        return f"""# {self.app_title}

Generated by the **Visual Flutter Full-Stack IDE**.

## Getting Started

1. Ensure the Flutter SDK is installed.
2. Install dependencies:
   ```bash
   flutter pub get
   ```
3. Run the application:
   ```bash
   flutter run
   ```
"""
